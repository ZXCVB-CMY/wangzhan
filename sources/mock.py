# 故意让第 4 条和第 5 条标题相同但 URL 不同（跨源），第 16 条超出 48 小时窗口
_DUPLICATE_URL_INDEX = 2  # 与第 3 条共用 URL，验证硬去重


def fetch(limit: int = 30) -> list[RawItem]:
    now = now_cn()
    out: list[RawItem] = []
    for i, (title, hours_ago, tags, summary, src) in enumerate(_MOCK):
        label = {"cnautonews": "中国汽车报", "autoinfo": "中国汽车工业信息网"}[src]
        item = RawItem(
            title=title,
            url=f"https://example.com/{src}/2026/11/{i + 1:02d}.html",
            source_id=src,
            source_label=label,
            published_at=iso(now - timedelta(hours=hours_ago)),
            summary_raw=summary,
            tags=tags,
            extra={"mock_index": i},
        )
        out.append(item)
    # 同 URL 的一条，验证 URL 完全一致时直接丢弃
    dup = out[_DUPLICATE_URL_INDEX]
    out.append(
        RawItem(
            title=dup.title + "（转载）",
            url=dup.url,
            source_id="mock-copy",
            source_label="示例转载",
            published_at=dup.published_at,
            summary_raw=dup.summary_raw,
            tags=list(dup.tags),
            extra={"mock_index": -1},
        )
    )
    return out[:limit]